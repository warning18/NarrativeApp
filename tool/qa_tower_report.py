#!/usr/bin/env python3
"""The Tower's balance report (QA, phase 2 of docs/proposals/the-tower-wave.md).

    flutter test test/qa_tower_sim_test.dart --plain-name batch  (with
        TOWER_SEEDS, TOWER_FIRST and TOWER_OUT set: see that test)
    python3 tool/qa_tower_report.py [--notes docs/qa/tower-balance-notes.md] \\
        build/tower.json [other.json ...] > docs/qa/tower-balance.md

Reads the batch JSON of test/qa_tower_sim_test.dart (Core's bot over a seed
batch, with no unlocks and with all of them) and prints the report: the win
rate of each floor, the median floor reached, how many reach floor 20 and
win floor 30, by profession, race and clan, the marks, and what the bot
took. The first file is the report; each further file (another seed range)
is a check that the figures do not move with the seeds. --notes puts a
hand-written file (the findings) after the first table, so a new batch keeps
them.
"""
import collections
import json
import statistics
import sys

TARGETS = {
    'median': (12, 16),
    'floor20': (25, 35),
    'top_none': (5, 10),
    'top_all': (15, 25),
}
BOSS = {10: 'boss', 20: 'boss', 30: 'top boss', 5: 'warden', 15: 'warden',
        25: 'warden'}


def pct(n, d):
    return 100.0 * n / d if d else 0.0


def load(path):
    with open(path) as f:
        return json.load(f)


def summary(runs):
    n = len(runs)
    reached = [r['floorReached'] for r in runs]
    return {
        'n': n,
        'median': statistics.median(reached),
        'mean': statistics.mean(reached),
        'f10': pct(sum(1 for f in reached if f >= 10), n),
        'f20': pct(sum(1 for f in reached if f >= 20), n),
        'top': pct(sum(1 for r in runs if r['status'] == 'won'), n),
        'marks': statistics.mean(r['marks'] for r in runs),
        'marks_median': statistics.median(r['marks'] for r in runs),
    }


def floors_table(runs, top):
    """Per floor: fought, won, lost there, the fight's win rate."""
    rows = []
    for floor in range(1, top + 1):
        fought = sum(1 for r in runs if r['floorReached'] >= floor)
        won = sum(1 for r in runs if r['floorsCleared'] >= floor)
        lost = fought - won
        rows.append((floor, fought, won, lost, pct(won, fought)))
    return rows


def group(runs, key):
    groups = collections.defaultdict(list)
    for r in runs:
        groups[r[key]].append(r)
    return groups


def check(value, low, high):
    return 'in' if low <= value <= high else 'OUT'


def main(args):
    notes = None
    if args[:1] == ['--notes']:
        notes = open(args[1]).read().rstrip()
        args = args[2:]
    paths = args
    if not paths:
        sys.exit(__doc__)
    data = load(paths[0])
    top = data['top']
    first, count = data['first'], data['count']
    none, all_ = data['cases']['none'], data['cases']['all']
    sn, sa = summary(none), summary(all_)
    out = []
    w = out.append
    w('# The Tower: balance report (QA, phase 2)')
    w('')
    w(f'Core\'s bot (`playTowerRun`, `lib/data/tower/tower_bot.dart`) over '
      f'{count:,} seeds ({first} to {first + count - 1}), once with no unlocks '
      f'and once with all of them, on the engine of #833 (v1.845). The bot is '
      f'naive by design: it takes the clan\'s die, better gear, a die, a skill, '
      f'a spell, the clan\'s stat, then a heal (a heal first below half health); '
      f'it never refuses a card. Generated by `tool/qa_tower_report.py` from '
      f'`test/qa_tower_sim_test.dart`; the guards in that test hold the targets '
      f'below on seeds 1 to 500 on every pull request.')
    w('')
    w('## Against the design\'s targets (tower-mechanics.md §11)')
    w('')
    w('| measure | target | no unlocks | all unlocks |')
    w('|---|---|---|---|')
    lo, hi = TARGETS['median']
    w(f'| median floor reached | {lo} to {hi} | **{sn["median"]:g}** '
      f'({check(sn["median"], lo, hi)}) | {sa["median"]:g} |')
    lo, hi = TARGETS['floor20']
    w(f'| reach floor 20 | {lo} to {hi}% | **{sn["f20"]:.1f}%** '
      f'({check(sn["f20"], lo, hi)}) | {sa["f20"]:.1f}% |')
    lo, hi = TARGETS['top_none']
    lo2, hi2 = TARGETS['top_all']
    w(f'| win floor {top} (the top) | {lo} to {hi}% none, {lo2} to {hi2}% all '
      f'| **{sn["top"]:.1f}%** ({check(sn["top"], lo, hi)}) '
      f'| **{sa["top"]:.1f}%** ({check(sa["top"], lo2, hi2)}) |')
    w(f'| reach floor 10 | | {sn["f10"]:.1f}% | {sa["f10"]:.1f}% |')
    w(f'| mean floor reached | | {sn["mean"]:.1f} | {sa["mean"]:.1f} |')
    w(f'| marks a run (mean, median) | | {sn["marks"]:.1f}, '
      f'{sn["marks_median"]:g} | {sa["marks"]:.1f}, {sa["marks_median"]:g} |')
    w('')
    if len(paths) > 1:
        w('**The figures hold on other seeds** (same method):')
        w('')
        w('| seeds | median none | floor 20 none | top none | top all |')
        w('|---|---|---|---|---|')
        w(f'| {first} to {first + count - 1} | {sn["median"]:g} | '
          f'{sn["f20"]:.1f}% | {sn["top"]:.1f}% | {sa["top"]:.1f}% |')
        for p in paths[1:]:
            d = load(p)
            a, b = summary(d['cases']['none']), summary(d['cases']['all'])
            w(f'| {d["first"]} to {d["first"] + d["count"] - 1} | '
              f'{a["median"]:g} | {a["f20"]:.1f}% | {a["top"]:.1f}% | '
              f'{b["top"]:.1f}% |')
        w('')
    if notes:
        w(notes)
        w('')
    w('## The climb floor by floor')
    w('')
    w('How many runs fought each floor, won it, and lost on it. The win rate '
      'is of the runs that got there. A floor that kills more than a fifth of '
      'those who reach it is marked.')
    w('')
    w('| floor | | fought (none) | won | lost here | win rate | '
      'win rate (all unlocks) |')
    w('|---|---|---|---|---|---|---|')
    fa = {f: rate for f, _, _, _, rate in floors_table(all_, top)}
    for floor, fought, won, lost, rate in floors_table(none, top):
        mark = ' **hard**' if fought and rate < 80 else ''
        w(f'| {floor} | {BOSS.get(floor, "")} | {fought} | {won} | {lost} | '
          f'{rate:.1f}%{mark} | {fa[floor]:.1f}% |')
    w('')
    deaths = [(f, l) for f, _, _, l, _ in floors_table(none, top)]
    worst = sorted(deaths, key=lambda x: -x[1])[:5]
    w('Floors that end the most runs (no unlocks): ' +
      ', '.join(f'{f} ({pct(l, len(none)):.1f}% of all runs)'
                for f, l in worst) + '.')
    w('')
    for key, title in (('profession', 'profession'), ('race', 'race'),
                       ('clan', 'clan')):
        w(f'## By {title}')
        w('')
        w(f'| {title} | runs (none) | median floor | floor 20 | top | '
          f'top with all unlocks |')
        w('|---|---|---|---|---|---|')
        gn, ga = group(none, key), group(all_, key)
        for name in sorted(set(gn) | set(ga)):
            s = summary(gn[name]) if name in gn else None
            t = summary(ga[name]) if name in ga else None
            if s:
                w(f'| {name} | {s["n"]} | {s["median"]:g} | {s["f20"]:.1f}% | '
                  f'{s["top"]:.1f}% | {t["top"]:.1f}% |' if t else
                  f'| {name} | {s["n"]} | {s["median"]:g} | {s["f20"]:.1f}% | '
                  f'{s["top"]:.1f}% | |')
            else:
                w(f'| {name} (all unlocks only) | | | | | {t["top"]:.1f}% |')
        spread = [summary(r)['top'] for r in gn.values()]
        w('')
        w(f'The top rate runs from {min(spread):.1f}% to {max(spread):.1f}% '
          f'across the {title}s (no unlocks).')
        w('')
    w('## What the bot takes')
    w('')
    w('The kind of card taken after each floor, over all runs with no '
      'unlocks (a card is taken after every floor that is won).')
    w('')
    kinds = collections.Counter()
    for r in none:
        kinds.update(r['taken'].values())
    total = sum(kinds.values())
    w('| kind | taken | share |')
    w('|---|---|---|')
    for kind, n in kinds.most_common():
        w(f'| {kind} | {n} | {pct(n, total):.1f}% |')
    w('')
    out_text = '\n'.join(out)
    print(out_text)


if __name__ == '__main__':
    main(sys.argv[1:])
